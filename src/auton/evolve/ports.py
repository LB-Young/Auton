from typing import Protocol

from auton.constitution.config import Principal
from auton.evolve.contracts import (
    ArenaCommand,
    ArenaControl,
    ArenaView,
    DiagnoseCommand,
    Diagnosis,
    EvolutionStatus,
    GenerationRecord,
    PlaybookEntry,
    Proposal,
    ProposalCommand,
    ReflectCommand,
    SubmitProposal,
)
from auton.kernel.ports import LifecycleHandle


class OptimizationInputPort(Protocol):
    async def optimization_request_ids(
        self, principal: Principal, project: str
    ) -> tuple[str, ...]: ...


class EvolutionPort(LifecycleHandle, OptimizationInputPort, Protocol):
    async def generations(
        self, principal: Principal, project: str
    ) -> tuple[GenerationRecord, ...]: ...
    def status(self) -> EvolutionStatus: ...
    async def diagnose(self, principal: Principal, command: DiagnoseCommand) -> Diagnosis: ...
    async def propose(self, principal: Principal, command: ProposalCommand) -> Proposal: ...
    async def reflect(self, principal: Principal, command: ReflectCommand) -> Proposal: ...
    async def proposals(self, principal: Principal, project: str) -> tuple[Proposal, ...]: ...
    async def proposal(self, principal: Principal, identity: str) -> Proposal: ...
    async def playbook(self, principal: Principal, project: str) -> tuple[PlaybookEntry, ...]: ...
    async def create_arena(self, principal: Principal, command: ArenaCommand) -> ArenaView: ...
    async def arena(self, principal: Principal, identity: str) -> ArenaView: ...
    async def arenas(self, principal: Principal, project: str) -> tuple[ArenaView, ...]: ...
    async def control_arena(
        self, principal: Principal, identity: str, command: ArenaControl
    ) -> ArenaView: ...
    async def submit(
        self, principal: Principal, proposal: str, command: SubmitProposal
    ) -> Proposal: ...
