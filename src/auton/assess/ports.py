from typing import Protocol

from auton.agent.contracts import AgentRun
from auton.assess.contracts import (
    Aggregate,
    AssessmentStatus,
    BatchEvaluation,
    BatchResult,
    BlindWindow,
    BlindWindowCommand,
    CalibrationCommand,
    CalibrationReport,
    CaseBank,
    Comparison,
    EvalCase,
    EvalJob,
    EvalReport,
    EvaluateCommand,
    ImportCases,
    JudgeObservation,
    SeedCommand,
    Signal,
    WindowView,
)
from auton.constitution.config import Principal
from auton.kernel.events import StoredEvent
from auton.kernel.ports import LifecycleHandle


class EvalStorePort(LifecycleHandle, Protocol):
    async def window_usage(self, owner: str, identity: str) -> int: ...
    async def split_digest(self, owner: str, revision: str, split: str) -> str: ...
    async def bank(self, principal: Principal) -> CaseBank: ...
    async def import_cases(self, principal: Principal, command: ImportCases) -> CaseBank: ...
    async def read_case(
        self, principal: Principal, case_id: str, revision: str, purpose: str
    ) -> EvalCase: ...
    async def open_window(
        self, principal: Principal, command: BlindWindowCommand
    ) -> BlindWindow: ...
    async def protected_case(self, owner: str, case_id: str, revision: str) -> EvalCase: ...
    async def consume_window(
        self, owner: str, window_id: str, bank_revision: str, split: str, request_id: str
    ) -> None: ...
    async def put(self, kind: str, owner: str, identity: str, data: dict[str, object]) -> None: ...
    async def get(self, kind: str, owner: str, identity: str) -> dict[str, object] | None: ...
    async def list(self, kind: str, owner: str) -> list[dict[str, object]]: ...


class CheckerPort(Protocol):
    async def check(
        self, principal: Principal, run: AgentRun, source: StoredEvent, case: EvalCase | None
    ) -> tuple[Signal, ...]: ...


class JudgePort(Protocol):
    async def evaluate(
        self,
        principal: Principal,
        identity: str,
        prompt: str,
        answer: str,
        public: bool,
        evidence: tuple[str, ...],
        actor_models: tuple[str, ...],
        actor_fingerprints: tuple[str, ...],
        evidence_text: dict[str, str] | None = None,
    ) -> JudgeObservation: ...


class AssessPort(LifecycleHandle, Protocol):
    async def windows(self, principal: Principal) -> tuple[WindowView, ...]: ...
    def status(self) -> AssessmentStatus: ...
    async def seed(self, principal: Principal, command: SeedCommand) -> CaseBank: ...
    async def report(self, principal: Principal, identity: str) -> EvalReport: ...
    async def batch(self, principal: Principal, command: BatchEvaluation) -> BatchResult: ...
    async def bank(self, principal: Principal) -> CaseBank: ...
    async def import_cases(self, principal: Principal, command: ImportCases) -> CaseBank: ...
    async def train_cases(self, principal: Principal) -> tuple[EvalCase, ...]: ...
    async def open_window(
        self, principal: Principal, command: BlindWindowCommand
    ) -> BlindWindow: ...
    async def evaluate(self, principal: Principal, command: EvaluateCommand) -> EvalJob: ...
    async def job(self, principal: Principal, identity: str) -> EvalJob: ...
    async def reports(self, principal: Principal, project: str) -> tuple[EvalReport, ...]: ...
    async def aggregate(self, principal: Principal, project: str) -> Aggregate: ...
    async def compare(self, principal: Principal, baseline: str, candidate: str) -> Comparison: ...
    async def calibrate(
        self, principal: Principal, command: CalibrationCommand
    ) -> CalibrationReport: ...
    async def calibrations(self, principal: Principal) -> tuple[CalibrationReport, ...]: ...
